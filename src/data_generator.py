import os
import numpy as np
import pandas as pd


def generate_financial_performance_data(start_date="2024-01-01", periods=24, seed=42):
    """
    Generates 24 months of synthetic financial performance data for a fictional
    diversified financial investment institution.
    """
    np.random.seed(seed)
    date_range = pd.date_range(start=start_date, periods=periods, freq="MS")

    records = []
    base_wealth = 4.2    # Million USD
    base_asset = 3.6     # Million USD
    base_advisory = 2.1  # Million USD
    base_treasury = 1.4  # Million USD

    # Base operating expenses
    base_personnel = 3.8
    base_tech = 1.6
    base_ops = 1.1
    base_comp = 0.6
    base_mktg = 0.5

    prev_total_rev = None

    for i, dt in enumerate(date_range):
        # Moderate upward trend with quarterly seasonal effects & small random variations
        trend_factor = 1.0 + (i * 0.008)
        seasonality = 1.05 if dt.month in [3, 6, 9, 12] else (0.96 if dt.month in [1, 8] else 1.0)
        noise = np.random.normal(1.0, 0.03, 4)

        rev_wealth = round(base_wealth * trend_factor * seasonality * noise[0], 3)
        rev_asset = round(base_asset * trend_factor * (1.0 + 0.5 * (seasonality - 1.0)) * noise[1], 3)
        rev_advisory = round(base_advisory * trend_factor * (seasonality ** 1.2) * noise[2], 3)
        rev_treasury = round(base_treasury * (1.0 + (i * 0.004)) * noise[3], 3)

        total_rev = round(rev_wealth + rev_asset + rev_advisory + rev_treasury, 3)

        # Expenses grow with inflation & business expansion but exhibit operational leverage
        exp_noise = np.random.normal(1.0, 0.02, 5)
        cost_trend = 1.0 + (i * 0.005)

        exp_pers = round(base_personnel * cost_trend * exp_noise[0], 3)
        exp_tech = round(base_tech * (1.0 + (i * 0.007)) * exp_noise[1], 3)  # Tech investment
        exp_ops = round(base_ops * cost_trend * exp_noise[2], 3)
        exp_comp = round(base_comp * (1.0 + (i * 0.003)) * exp_noise[3], 3)
        exp_mktg = round(base_mktg * seasonality * exp_noise[4], 3)

        total_exp = round(exp_pers + exp_tech + exp_ops + exp_comp + exp_mktg, 3)
        net_profit = round(total_rev - total_exp, 3)
        profit_margin_pct = round((net_profit / total_rev) * 100, 2)

        if prev_total_rev is None:
            mom_growth_pct = 0.0
        else:
            mom_growth_pct = round(((total_rev - prev_total_rev) / prev_total_rev) * 100, 2)
        prev_total_rev = total_rev

        records.append({
            "date": dt.strftime("%Y-%m-%d"),
            "month_name": dt.strftime("%b %Y"),
            "rev_wealth_management": rev_wealth,
            "rev_asset_management": rev_asset,
            "rev_investment_advisory": rev_advisory,
            "rev_treasury_services": rev_treasury,
            "total_revenue": total_rev,
            "exp_personnel": exp_pers,
            "exp_technology": exp_tech,
            "exp_operations": exp_ops,
            "exp_compliance_risk": exp_comp,
            "exp_marketing": exp_mktg,
            "total_expenses": total_exp,
            "net_profit": net_profit,
            "profit_margin_pct": profit_margin_pct,
            "mom_revenue_growth_pct": mom_growth_pct,
            "data_label": "SYNTHETIC"
        })

    df = pd.DataFrame(records)
    return df


def generate_portfolio_price_data(start_date="2024-01-01", periods=504, seed=42):
    """
    Generates 2 years (~504 trading days) of correlated synthetic daily asset prices
    for Equities, Government Bonds, Gold, and Foreign Exchange.
    """
    np.random.seed(seed)
    # Generate business trading days
    date_range = pd.bdate_range(start=start_date, periods=periods)

    # Asset specifications:
    # Asset 0: Equities (Global Equity Index) -> expected annual return: 11%, vol: 17%
    # Asset 1: Government Bonds (10Y Sovereign Bond) -> expected annual return: 4.5%, vol: 5.5%
    # Asset 2: Gold (Precious Metals) -> expected annual return: 8.0%, vol: 13.5%
    # Asset 3: Foreign Exchange (Global FX Basket) -> expected annual return: 2.5%, vol: 8.0%
    annual_returns = np.array([0.11, 0.045, 0.08, 0.025])
    annual_vols = np.array([0.17, 0.055, 0.135, 0.08])

    dt = 1.0 / 252.0
    daily_mu = (annual_returns - 0.5 * annual_vols ** 2) * dt
    daily_sigma = annual_vols * np.sqrt(dt)

    # Realistic correlation structure:
    # Bonds & Gold serve as diversifiers/hedges against equity sell-offs
    corr_matrix = np.array([
        [ 1.00, -0.15, -0.05,  0.20],  # Equities
        [-0.15,  1.00,  0.12, -0.10],  # Government Bonds
        [-0.05,  0.12,  1.00, -0.22],  # Gold
        [ 0.20, -0.10, -0.22,  1.00]   # Foreign Exchange
    ])

    # Cholesky decomposition for correlated standard normal shocks
    L = np.linalg.cholesky(corr_matrix)

    # Generate uncorrelated random normal shocks
    uncorr_shocks = np.random.normal(0, 1, size=(periods - 1, 4))
    # Transform to correlated shocks
    corr_shocks = uncorr_shocks @ L.T

    # Calculate daily simple returns using Geometric Brownian Motion
    daily_returns = np.exp(daily_mu + daily_sigma * corr_shocks) - 1.0

    # Initial base price = 100.0 for all assets
    prices = np.zeros((periods, 4))
    prices[0] = [100.0, 100.0, 100.0, 100.0]

    for t in range(1, periods):
        prices[t] = prices[t - 1] * (1.0 + daily_returns[t - 1])

    df = pd.DataFrame({
        "date": date_range.strftime("%Y-%m-%d"),
        "equities": np.round(prices[:, 0], 2),
        "bonds": np.round(prices[:, 1], 2),
        "gold": np.round(prices[:, 2], 2),
        "fx": np.round(prices[:, 3], 2),
        "data_label": "SYNTHETIC"
    })
    return df


def generate_all_datasets(output_dir="data"):
    """Creates the data directory and generates both CSV datasets."""
    os.makedirs(output_dir, exist_ok=True)

    fin_df = generate_financial_performance_data()
    fin_path = os.path.join(output_dir, "synthetic_financial_performance.csv")
    fin_df.to_csv(fin_path, index=False)
    print(f"Generated {fin_path} ({len(fin_df)} monthly records)")

    port_df = generate_portfolio_price_data()
    port_path = os.path.join(output_dir, "synthetic_portfolio_prices.csv")
    port_df.to_csv(port_path, index=False)
    print(f"Generated {port_path} ({len(port_df)} daily records)")


if __name__ == "__main__":
    generate_all_datasets()
